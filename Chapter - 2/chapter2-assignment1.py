# Program to take two numbers and prints
# Their sum, difference, product
# Whether first number greater than second
num1= int(input("Enter a number1: "))
num2= int(input("Enter a number2: "))
print("Sum of numbers is:", num1 + num2)
print("Difference of numbers is:", num1 - num2)
print("Product of numbers is:", num1 * num2)
print("Is First number greater than second:", num1 > num2 )
